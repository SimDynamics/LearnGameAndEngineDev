package com.learngraphicsprogramming.app.narration

import com.learngraphicsprogramming.app.narration.phonemes.EnglishMisakiG2P
import com.learngraphicsprogramming.app.narration.phonemes.EnglishMisakiResources
import com.learngraphicsprogramming.app.narration.phonemes.MisakiPartOfSpeechTagger
import java.io.File
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test

class ManualEnglishPronunciationsTest {
    @Test fun everyManualEntryHasAnExplicitCompiledPronunciation() {
        if (System.getenv("LGP_MANUAL_ENGLISH_GENERATE") == "true") return
        assertEquals(ManualEnglishTerms.entries.map { it.id }.toSet(), ManualEnglishPronunciations.phones.keys)
        assertTrue(ManualEnglishPronunciations.phones.values.all { it.isNotBlank() })
    }

    @Test fun compiledPronunciationsMatchThePinnedVerifiedMisakiFrontend() {
        val path = System.getenv("LGP_MISAKI_DIRECTORY")
        assumeTrue("Set LGP_MISAKI_DIRECTORY to existing verified dictionaries for regeneration", path != null)
        val directory = File(requireNotNull(path))
        var tags = emptyList<String>()
        val generated = linkedMapOf<String, String>()
        EnglishMisakiG2P(openResource = { name ->
            require(name in setOf("us_gold.json", "us_silver.json"))
            File(directory, name).inputStream()
        }, partOfSpeech = MisakiPartOfSpeechTagger { words ->
            require(words.size == tags.size) { "Manual POS count ${tags.size} differs from alias tokens $words" }
            tags
        }).use { english ->
            ManualEnglishTerms.entries.forEach { entry ->
                tags = entry.tags
                generated[entry.id] = english.phonemize(entry.englishText)
            }
        }
        if (System.getenv("LGP_MANUAL_ENGLISH_GENERATE") == "true") {
            val output = File("build/reports/manual-english/ManualEnglishPronunciations.kt")
            output.parentFile.mkdirs()
            output.writeText(buildString {
                append("package com.learngraphicsprogramming.app.narration\n\n")
                append("/** Generated by ManualEnglishPronunciationsTest using verified Misaki ${EnglishMisakiResources.revision}.\n")
                append(" * Explicit POS/aliases are in ManualEnglishTerms; no English models are required at runtime. */\n")
                append("internal object ManualEnglishPronunciations {\n    val phones = mapOf(\n")
                generated.forEach { (id, phones) -> append("        \"$id\" to \"$phones\",\n") }
                append("    )\n    fun phonemes(entry: ManualEnglishTerms.Entry): String = phones.getValue(entry.id)\n}\n")
            }, Charsets.UTF_8)
        } else assertEquals(generated, ManualEnglishPronunciations.phones)
    }
}

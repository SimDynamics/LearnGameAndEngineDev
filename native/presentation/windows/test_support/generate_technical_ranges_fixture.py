"""Generate native range fixtures by running unchanged canonical Kotlin classes.

Uses existing local Java/Kotlin outputs only; never builds Android or downloads.
The Android classes take precedence over Windows speech adaptations in the jar.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[4]
APP = ROOT / "app/src/main/java/com/learngraphicsprogramming/app/narration"
CLASSES = ROOT / "app/build/intermediates/built_in_kotlinc/debug/compileDebugKotlin/classes"
OUT = ROOT / "out/qa/jvm-technical"
FIXTURE = ROOT / "native/presentation/windows/fixtures/technical_ranges_android.tsv"
NAMES = ("ProgrammingTechnicalRanges", "ManualEnglishTerms", "SpanishTechnicalSpeech",
         "EnglishTechnicalSpeech", "FrenchSpeechSymbols", "ManualEnglishSpeech", "NarrationLanguage")


def verify_fixture():
    lines = FIXTURE.read_text(encoding="utf-8").splitlines()
    for number, line in enumerate(lines, 1):
        if line.endswith((" ", "\t")):
            raise RuntimeError(f"Android range fixture has trailing whitespace at line {number}")
        if line and not line.startswith("#"):
            cells = line.split("\t")
            if len(cells) != 4 or any(not re.fullmatch(r"-|\d+:\d+(?:,\d+:\d+)*", cell) for cell in cells[2:]):
                raise RuntimeError(f"Invalid Android range fixture at line {number}; use '-' for empty range lists")
    headers = [line.split(" ", 3) for line in lines if line.startswith("# sha256 ")]
    expected = {(APP / f"{name}.kt").relative_to(ROOT).as_posix() for name in NAMES}
    if {header[3] for header in headers} != expected or len(headers) != len(expected):
        raise RuntimeError("The Android range fixture has an incomplete or unexpected provenance header")
    for _, _, checksum, relative in headers:
        source = ROOT / relative
        if hashlib.sha256(source.read_bytes()).hexdigest() != checksum:
            raise RuntimeError(f"Android technical-range fixture is stale: {relative}; regenerate with its canonical Kotlin reference")
    print(f"Canonical Android range fixture matches all {len(headers)} current source hashes.")


def encode(value):
    return value.replace("\\", "\\\\").replace("\t", "\\t").replace("\r", "\\r").replace("\n", "\\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    metadata = ["# Canonical Android ProgrammingTechnicalRanges UTF-16 ranges; generated by test_support/generate_technical_ranges_fixture.py",
                "# locale<TAB>escaped original UTF-8 source<TAB>start:end fragments<TAB>start:end hidden wrappers; '-' means no ranges"]
    for name in NAMES:
        source = APP / f"{name}.kt"
        compiled = CLASSES / "com/learngraphicsprogramming/app/narration" / f"{name}.class"
        if not compiled.is_file() or compiled.stat().st_mtime_ns < source.stat().st_mtime_ns:
            raise RuntimeError(f"Canonical class is older than its unchanged source: {name}")
        metadata.append(f"# sha256 {hashlib.sha256(source.read_bytes()).hexdigest()} {source.relative_to(ROOT).as_posix()}")
    cases = set()
    def add(value):
        if value and "\0" not in value:
            cases.add(value)
    entries = re.findall(r'\bterm\("([^"]+)"', (APP / "ManualEnglishTerms.kt").read_text(encoding="utf-8"))
    for word in entries:
        for template in ("{0}", "Lee {0} y continúa.", '"{0}"', "'{0}'", "`{0}`", "```{0}```",
                         "std::{0}", "std::{0}(2);", "<{0}>", "{0}(2);", "object.{0}(2);",
                         "int {0} = 2;", "const {0}& value = other;", "std::vector<{0}> values{{1}};",
                         "El tipo {0} conserva su función.", "The type {0} is a keyword.", "Le type {0} reste disponible.",
                         "La palabra clave {0} conserva su función.", "The identifier {0} remains available.",
                         "Le mot-clé {0} reste disponible.", "La función {0} funciona.", "The function {0} works.",
                         "La fonction {0} reste disponible.", "Le membre nommé {0} reste disponible.",
                         "La directiva {0} existe.", "The directive {0} exists.", "La directive {0} existe."):
            add(template.format(word))
    operators = ("<=> <<= >>= ->* :: ## && || == != <= >= << >> ++ -- += -= *= /= %= &= |= ^= -> .* ".split() +
                 list("#{}[]<>=+*/\\%&|^~_!;():,.-"))
    for symbol in operators:
        for value in (symbol, f"a {symbol} b", f"left {symbol} right", f"a{symbol}b", f"{symbol}ready", f"ready{symbol}",
                      f"el operador {symbol} conserva su lugar.", f"the operator {symbol} keeps its place.",
                      f"L'opérateur {symbol} reste disponible.", f"Los símbolos {symbol} son visibles.",
                      f"Symbols: {symbol}, then continue.", f"Les signes {symbol} restent visibles.",
                      f'"{symbol}"', f"'{symbol}'", f"`{symbol}`", f"```{symbol}```", f'"value {symbol} next"',
                      f'"unfinished {symbol} next', f"attention{symbol} continue", f"https://example.org/{symbol}value",
                      f"\\(x {symbol} y\\)", f'int value = 2; std::cout << "{symbol}";',
                      f"function(2{symbol}3)", f"custom_name(2{symbol}3)"):
            add(value)
    for cue in ("place", "put", "include", "punctuation", "punctuation mark", "with", "without", "the", "each", "every",
                "mettez", "mets", "mettre", "écrivez", "écris", "écrire", "ajoutez", "ajoutons", "ajoutent", "insérez",
                "placez", "placer", "supprimez", "retirez", "terminer par", "finit par", "CARACTÈRE", "ÉCRIS", "CARÁCTER", "AÑADE"):
        for suffix in ("", ".", " pour terminer.", " à chaque ligne ; conserve la prose.", " para terminar.", " terminates the statement."):
            add(f"{cue} ;{suffix}")
    for text in ("La letra número, letra nombre, carácter nñ, carácter n2, carácter n_1; la n y una a. \\nueva, \\tarea, \\z y alfa\\n; superletra n y áletra n.",
                 "carácter q)", "custom_name", "Foo::Bar<int>", '"a\\n"', "1e-3", "0x10", "2.0e+4f", "::", "--",
                 "El operador es << y conserva la secuencia.", "L'opérateur est << et garde sa place.", "The operator is << and keeps its place.",
                 "😀 Avant ```cpp\r\nstd::cout << \"C++\";\r\n``` après et `return 0;`.",
                 "Ticks `   ` et ```\n \n``` visibles.", "`sans fermeture", "La formule `\\(x+1\\)` reste mathématique.",
                 "C++", "C++20", "`C++`", "Aprende C++ y C++20.", 'std::cout << "C++";', "beforeC++word", "C+++", "C++/CLI"):
        add(text)
    # Canonical regression inputs cover language-specific ambiguity, semicolon
    # enumerations, context spacing, escapes and mathematical/URL exclusions.
    for name in ("ProgrammingTechnicalRangesTest", "ManualEnglishTermsTest", "EnglishTechnicalSpeechTest", "FrenchSpeechSymbolsTest", "SpanishTechnicalSpeechTest"):
        path = ROOT / "app/src/test/java/com/learngraphicsprogramming/app/narration" / f"{name}.kt"
        if not path.is_file():
            continue
        for raw in re.findall(r'"((?:\\.|[^"\\])*)"', path.read_text(encoding="utf-8")):
            if "$" in raw or len(raw) > 600:
                continue
            try:
                value = json.loads('"' + raw + '"')
            except json.JSONDecodeError:
                continue
            if " " in value or value in operators:
                add(value)
    rows = [f"{locale}\t{encode(text)}" for text in sorted(cases) for locale in ("es", "en", "fr")]
    source = OUT / "cases.tsv"
    source.write_text("\n".join(metadata + rows) + "\n", encoding="utf-8", newline="\n")
    config = json.loads((ROOT / "out/narration/runtime.json").read_text(encoding="utf-8"))
    java = config.get("javaExecutable") or "java"
    harness = Path(__file__).with_name("TechnicalRangesReference.java")
    # Keep every original Kotlin method/module name together. Only the enum's
    # Android resource-label glue yields to the current worker's identical
    # language/tag/locale enum, so no R/Context class is needed on this JVM.
    canonical = OUT / "canonical-android-classes.jar"
    with zipfile.ZipFile(canonical, "w", compression=zipfile.ZIP_STORED) as archive:
        for compiled in CLASSES.rglob("*.class"):
            if compiled.name.startswith("NarrationLanguage"):
                continue
            archive.write(compiled, compiled.relative_to(CLASSES).as_posix())
    subprocess.run([java, "-cp", str(canonical) + ";" + config["classpath"], str(harness), str(source), str(FIXTURE)], check=True, cwd=ROOT)
    subprocess.run([java, "-cp", config["classpath"], str(harness), str(source), str(OUT / "windows-adapted.tsv")], check=True, cwd=ROOT)
    print(f"Generated {len(rows)} canonical Android cases; Windows-adapted oracle retained separately under out/qa/jvm-technical.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true", help="Verify source hashes only, without Java, Gradle, downloads or writes")
    arguments = parser.parse_args()
    if arguments.verify:
        verify_fixture()
    else:
        main()
